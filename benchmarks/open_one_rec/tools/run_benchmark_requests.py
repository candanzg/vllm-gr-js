"""Run benchmark requests against a vLLM-compatible chat completions endpoint.

Usage:
    python benchmarks/open_one_rec/tools/run_benchmark_requests.py \
      --input data/bench/requests.jsonl \
      --endpoint http://127.0.0.1:8000/v1/chat/completions \
      --output results/bench_summary.json \
      --max-concurrency 64

Notes:
    - The input file should be generated by generate_benchmark_requests.py.
    - Cache hit rate is computed from the delta of vllm:prefix_cache_queries
      and vllm:prefix_cache_hits on the Prometheus /metrics endpoint.
    - The script prints summary metrics to stdout and can also save them as JSON.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import logging
import math
import re
import statistics
import time
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable
from urllib.parse import urlparse

import aiohttp
from vllm.benchmarks.lib.endpoint_request_func import StreamedResponseHandler

LOGGER = logging.getLogger(__name__)

METRIC_LINE_RE = re.compile(r"^(?P<name>[a-zA-Z_:][a-zA-Z0-9_:]*)({[^}]*})?\s+(?P<value>[-+0-9.eE]+)$")


@dataclass
class RequestResult:
    request_id: str
    source_unique_index: int | None
    request_group: str
    success: bool
    start_time: float
    end_time: float
    ttft: float | None = None
    latency: float | None = None
    output_tokens: int = 0
    chunks: int = 0
    error: str | None = None


@dataclass
class RunSummary:
    total_requests: int
    successful_requests: int
    failed_requests: int
    duration_s: float
    request_throughput_req_s: float
    p99_request_throughput_req_s: float
    output_token_throughput_tok_s: float
    p99_output_token_throughput_tok_s: float
    mean_ttft_ms: float | None
    p99_ttft_ms: float | None
    mean_latency_ms: float | None
    p99_latency_ms: float | None
    t99_latency_ms: float | None
    cache_hit_rate: float | None
    total_output_tokens: int
    duplicate_request_rate: float
    per_request_results: list[dict[str, Any]] = field(default_factory=list)


def _percentile(values: list[float], percentile: float) -> float | None:
    if not values:
        return None
    if len(values) == 1:
        return values[0]
    ordered = sorted(values)
    rank = (len(ordered) - 1) * percentile
    lower = math.floor(rank)
    upper = math.ceil(rank)
    if lower == upper:
        return ordered[lower]
    lower_value = ordered[lower]
    upper_value = ordered[upper]
    return lower_value + (upper_value - lower_value) * (rank - lower)


def _load_requests(input_path: str) -> list[dict[str, Any]]:
    path = Path(input_path)
    requests: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as file:
        for line_number, line in enumerate(file, start=1):
            payload = line.strip()
            if not payload:
                continue
            try:
                request = json.loads(payload)
            except json.JSONDecodeError as error:
                raise ValueError(f"Failed to decode JSONL line {line_number} in {path}") from error
            requests.append(request)
    if not requests:
        raise ValueError(f"No requests found in {path}")
    return requests


def _derive_metrics_url(endpoint: str) -> str:
    parsed = urlparse(endpoint)
    return f"{parsed.scheme}://{parsed.netloc}/metrics"


def _parse_prometheus_metrics(text: str) -> dict[str, float]:
    metrics: dict[str, float] = {}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        match = METRIC_LINE_RE.match(stripped)
        if not match:
            continue
        name = match.group("name")
        value = float(match.group("value"))
        metrics[name] = metrics.get(name, 0.0) + value
    return metrics


async def _fetch_metrics(session: aiohttp.ClientSession, metrics_url: str) -> dict[str, float] | None:
    try:
        async with session.get(metrics_url) as response:
            if response.status != 200:
                LOGGER.warning("Metrics endpoint returned status %s: %s", response.status, metrics_url)
                return None
            payload = await response.text()
            return _parse_prometheus_metrics(payload)
    except aiohttp.ClientError as error:
        LOGGER.warning("Failed to fetch metrics from %s: %s", metrics_url, error)
        return None


def _compute_cache_hit_rate(before: dict[str, float] | None, after: dict[str, float] | None) -> float | None:
    if before is None or after is None:
        return None
    query_delta = after.get("vllm:prefix_cache_queries", 0.0) - before.get("vllm:prefix_cache_queries", 0.0)
    hit_delta = after.get("vllm:prefix_cache_hits", 0.0) - before.get("vllm:prefix_cache_hits", 0.0)
    if query_delta <= 0:
        return None
    return hit_delta / query_delta


def _build_headers(api_key: str | None) -> dict[str, str]:
    headers = {"Content-Type": "application/json"}
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"
    return headers


def _request_output_tokens(payload: dict[str, Any], usage_tokens: int) -> int:
    if usage_tokens > 0:
        return usage_tokens
    max_tokens = payload.get("max_tokens")
    if isinstance(max_tokens, int) and max_tokens > 0:
        return max_tokens
    return 0


async def _run_single_request(
    session: aiohttp.ClientSession,
    endpoint: str,
    payload: dict[str, Any],
    semaphore: asyncio.Semaphore,
    headers: dict[str, str],
) -> RequestResult:
    request_id = str(payload.get("request_id", "")) or f"request-{time.perf_counter_ns()}"
    source_unique_index = payload.get("source_unique_index")
    request_group = str(payload.get("request_group", "unknown"))
    request_body = {k: v for k, v in payload.items() if k not in {"request_id", "request_group", "repeat_round", "source_unique_index"}}
    request_body["stream"] = True
    request_body["stream_options"] = {"include_usage": True}

    async with semaphore:
        start_time = time.perf_counter()
        ttft: float | None = None
        chunks = 0
        output_tokens = 0
        try:
            async with session.post(endpoint, json=request_body, headers=headers) as response:
                if response.status != 200:
                    error_text = await response.text()
                    return RequestResult(
                        request_id=request_id,
                        source_unique_index=source_unique_index,
                        request_group=request_group,
                        success=False,
                        start_time=start_time,
                        end_time=time.perf_counter(),
                        error=f"HTTP {response.status}: {error_text[:500]}",
                    )

                handler = StreamedResponseHandler()
                async for raw_chunk in response.content.iter_any():
                    for message in handler.add_chunk(raw_chunk.strip()):
                        if not message or message.startswith(":"):
                            continue
                        data = message.removeprefix("data: ")
                        if data == "[DONE]":
                            continue
                        timestamp = time.perf_counter()
                        parsed = json.loads(data)
                        if parsed.get("choices"):
                            if ttft is None:
                                ttft = timestamp - start_time
                            chunks += 1
                        usage = parsed.get("usage")
                        if isinstance(usage, dict):
                            output_tokens = int(usage.get("completion_tokens") or 0)

                end_time = time.perf_counter()
                latency = end_time - start_time
                return RequestResult(
                    request_id=request_id,
                    source_unique_index=source_unique_index,
                    request_group=request_group,
                    success=True,
                    start_time=start_time,
                    end_time=end_time,
                    ttft=ttft,
                    latency=latency,
                    output_tokens=_request_output_tokens(request_body, output_tokens),
                    chunks=chunks,
                )
        except Exception as error:
            return RequestResult(
                request_id=request_id,
                source_unique_index=source_unique_index,
                request_group=request_group,
                success=False,
                start_time=start_time,
                end_time=time.perf_counter(),
                error=str(error),
            )


def _bucketed_throughput(
    results: list[RequestResult],
    value_getter: Callable[[RequestResult], int],
    window_s: float = 1.0,
) -> list[float]:
    if not results:
        return []
    first_start = min(result.start_time for result in results)
    buckets: Counter[int] = Counter()
    for result in results:
        if not result.success:
            continue
        bucket_index = int((result.end_time - first_start) / window_s)
        buckets[bucket_index] += value_getter(result)
    return [value / window_s for _, value in sorted(buckets.items())]


def _build_summary(
    results: list[RequestResult],
    duration_s: float,
    cache_hit_rate: float | None,
) -> RunSummary:
    successful_results = [result for result in results if result.success]
    failed_results = [result for result in results if not result.success]
    ttfts = [result.ttft * 1000.0 for result in successful_results if result.ttft is not None]
    latencies = [result.latency * 1000.0 for result in successful_results if result.latency is not None]
    total_output_tokens = sum(result.output_tokens for result in successful_results)
    request_throughput_buckets = _bucketed_throughput(
        successful_results,
        lambda _result: 1,
        window_s=1.0,
    )
    token_throughput_buckets = _bucketed_throughput(
        successful_results,
        lambda result: result.output_tokens,
        window_s=1.0,
    )
    duplicate_request_count = sum(1 for result in results if result.request_group == "repeat")

    return RunSummary(
        total_requests=len(results),
        successful_requests=len(successful_results),
        failed_requests=len(failed_results),
        duration_s=duration_s,
        request_throughput_req_s=(len(successful_results) / duration_s) if duration_s > 0 else 0.0,
        p99_request_throughput_req_s=_percentile(request_throughput_buckets, 0.99) or 0.0,
        output_token_throughput_tok_s=(total_output_tokens / duration_s) if duration_s > 0 else 0.0,
        p99_output_token_throughput_tok_s=_percentile(token_throughput_buckets, 0.99) or 0.0,
        mean_ttft_ms=statistics.mean(ttfts) if ttfts else None,
        p99_ttft_ms=_percentile(ttfts, 0.99),
        mean_latency_ms=statistics.mean(latencies) if latencies else None,
        p99_latency_ms=_percentile(latencies, 0.99),
        t99_latency_ms=_percentile(latencies, 0.99),
        cache_hit_rate=cache_hit_rate,
        total_output_tokens=total_output_tokens,
        duplicate_request_rate=(duplicate_request_count / len(results)) if results else 0.0,
        per_request_results=[
            {
                "request_id": result.request_id,
                "request_group": result.request_group,
                "source_unique_index": result.source_unique_index,
                "success": result.success,
                "ttft_ms": None if result.ttft is None else result.ttft * 1000.0,
                "latency_ms": None if result.latency is None else result.latency * 1000.0,
                "output_tokens": result.output_tokens,
                "chunks": result.chunks,
                "error": result.error,
            }
            for result in results
        ],
    )


async def _run(args: argparse.Namespace) -> RunSummary:
    requests = _load_requests(args.input)
    semaphore = asyncio.Semaphore(args.max_concurrency)
    timeout = aiohttp.ClientTimeout(total=args.request_timeout_s)
    connector = aiohttp.TCPConnector(limit=args.max_concurrency)
    headers = _build_headers(args.api_key)
    metrics_url = args.metrics_url or _derive_metrics_url(args.endpoint)

    async with aiohttp.ClientSession(timeout=timeout, connector=connector) as session:
        before_metrics = await _fetch_metrics(session, metrics_url)
        start_time = time.perf_counter()
        tasks = [
            asyncio.create_task(
                _run_single_request(
                    session=session,
                    endpoint=args.endpoint,
                    payload=request,
                    semaphore=semaphore,
                    headers=headers,
                )
            )
            for request in requests
        ]
        results = await asyncio.gather(*tasks)
        end_time = time.perf_counter()
        after_metrics = await _fetch_metrics(session, metrics_url)

    duration_s = end_time - start_time
    cache_hit_rate = _compute_cache_hit_rate(before_metrics, after_metrics)
    return _build_summary(results=results, duration_s=duration_s, cache_hit_rate=cache_hit_rate)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run JSONL benchmark requests against a vLLM chat/completions endpoint.")
    parser.add_argument("--input", required=True, help="Input JSONL generated by generate_benchmark_requests.py.")
    parser.add_argument("--endpoint", required=True, help="Full chat/completions URL, for example http://127.0.0.1:8000/v1/chat/completions.")
    parser.add_argument("--output", help="Optional output JSON path for the benchmark summary.")
    parser.add_argument("--metrics-url", help="Optional Prometheus metrics URL. Default: derived from endpoint host as /metrics.")
    parser.add_argument("--api-key", help="Optional bearer token for the endpoint.")
    parser.add_argument(
        "--max-concurrency",
        type=int,
        default=32,
        help="Maximum number of in-flight requests. Default: 32.",
    )
    parser.add_argument(
        "--request-timeout-s",
        type=float,
        default=600.0,
        help="Per-run client timeout in seconds. Default: 600.",
    )
    parser.add_argument(
        "--print-errors",
        action="store_true",
        help="Print failed request details after the summary.",
    )
    return parser.parse_args()


def _summary_to_dict(summary: RunSummary) -> dict[str, Any]:
    return {
        "total_requests": summary.total_requests,
        "successful_requests": summary.successful_requests,
        "failed_requests": summary.failed_requests,
        "duration_s": summary.duration_s,
        "request_throughput_req_s": summary.request_throughput_req_s,
        "p99_request_throughput_req_s": summary.p99_request_throughput_req_s,
        "output_token_throughput_tok_s": summary.output_token_throughput_tok_s,
        "p99_output_token_throughput_tok_s": summary.p99_output_token_throughput_tok_s,
        "mean_ttft_ms": summary.mean_ttft_ms,
        "p99_ttft_ms": summary.p99_ttft_ms,
        "mean_latency_ms": summary.mean_latency_ms,
        "p99_latency_ms": summary.p99_latency_ms,
        "t99_latency_ms": summary.t99_latency_ms,
        "cache_hit_rate": summary.cache_hit_rate,
        "total_output_tokens": summary.total_output_tokens,
        "duplicate_request_rate": summary.duplicate_request_rate,
        "per_request_results": summary.per_request_results,
    }


def main() -> None:
    args = parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    summary = asyncio.run(_run(args))

    print("============ Benchmark Result ============")
    print(f"Total requests:                 {summary.total_requests}")
    print(f"Successful requests:            {summary.successful_requests}")
    print(f"Failed requests:                {summary.failed_requests}")
    print(f"Benchmark duration (s):         {summary.duration_s:.2f}")
    print(f"Request throughput (req/s):     {summary.request_throughput_req_s:.2f}")
    print(f"P99 request throughput (req/s): {summary.p99_request_throughput_req_s:.2f}")
    print(f"Output throughput (tok/s):      {summary.output_token_throughput_tok_s:.2f}")
    print(f"P99 output throughput (tok/s):  {summary.p99_output_token_throughput_tok_s:.2f}")
    print(f"Mean TTFT (ms):                 {summary.mean_ttft_ms:.2f}" if summary.mean_ttft_ms is not None else "Mean TTFT (ms):                 n/a")
    print(f"P99 TTFT (ms):                  {summary.p99_ttft_ms:.2f}" if summary.p99_ttft_ms is not None else "P99 TTFT (ms):                  n/a")
    print(f"Mean latency (ms):              {summary.mean_latency_ms:.2f}" if summary.mean_latency_ms is not None else "Mean latency (ms):              n/a")
    print(f"P99 latency (ms):               {summary.p99_latency_ms:.2f}" if summary.p99_latency_ms is not None else "P99 latency (ms):               n/a")
    print(f"T99 latency (ms):               {summary.t99_latency_ms:.2f}" if summary.t99_latency_ms is not None else "T99 latency (ms):               n/a")
    if summary.cache_hit_rate is None:
        print("Cache hit rate:                 n/a")
    else:
        print(f"Cache hit rate:                 {summary.cache_hit_rate:.2%}")
    print("==========================================")

    if args.print_errors:
        failed = [item for item in summary.per_request_results if not item["success"]]
        for item in failed:
            print(f"[FAILED] {item['request_id']}: {item['error']}")

    if args.output:
        output_path = Path(args.output)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        with output_path.open("w", encoding="utf-8") as file:
            json.dump(_summary_to_dict(summary), file, indent=2, ensure_ascii=False)
        LOGGER.info("Wrote benchmark summary to %s", output_path)


if __name__ == "__main__":
    main()
